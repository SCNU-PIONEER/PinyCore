#include "WLController.hpp"

#include <cmath>

using namespace CHASSIS::BIPEDAL;

WLController::WLController() = default;

void WLController::load(const States_u &_refX, const States_u &_curX)
{
    for (uint8_t i = 0; i < 6; i++) {
        refX_[i][0] = _refX._[i];
        curX_[i][0] = _curX._[i];
    }
}

const Matrix<2, 1> &WLController::solve(float _l, bool _isFloating)
{
    float x = _l;
    float arrayK[2 * 6] = {
        (843.49554066371820227f * powf(x, 2)) - (269.4788639088058062f * x) -
                (1007.291795324041459f * powf(x, 3)) - (3.6870612670499269825f),
        (277.52565100889881933f * powf(x, 2)) - (69.883854246752008521f * x) -
                (389.76801732145736423f * powf(x, 3)) +
                (2.8424462203432718788f),
        (7.5715341911149645071f * powf(x, 2)) - (2.6771026391970571545f * x) -
                (9.4572453511010827754f * powf(x, 3)) -
                (0.94094959171123959685f),
        (13.854828093377424381f * x) - (41.474366145870170897f * powf(x, 2)) +
                (41.261940611718316063f * powf(x, 3)) -
                (5.2707188397751476572f),
        (560.83981254619857282f * powf(x, 2)) - (177.39295193350108093f * x) -
                (721.85278627785885419f * powf(x, 3)) +
                (35.870012297308022653f),
        (89.392691944965761763f * powf(x, 2)) - (27.471271695255179424f * x) -
                (111.56318631820293774f * powf(x, 3)) +
                (5.0251495988233134682f),
        (556.92138459629109093f * powf(x, 2)) - (173.55081021092695437f * x) -
                (813.93213514825049515f * powf(x, 3)) +
                (49.362715609208557055f),
        (3.2634771210466260172f * x) - (22.208258798279842949f * powf(x, 2)) +
                (24.517431431788441643f * powf(x, 3)) +
                (2.6206884572971391734f),
        (1.7353493174978549263f * powf(x, 2)) - (0.12206403732458021016f * x) -
                (10.99732266822900506f * powf(x, 3)) +
                (0.99557187363112809031f),
        (41.179117443060093251f * powf(x, 2)) - (14.79439485040865776f * x) -
                (62.40723907324420594f * powf(x, 3)) + (4.6748641340776497799f),
        (195.18636504122173392f * x) - (545.23394424419882398f * powf(x, 2)) +
                (591.09493769711002642f * powf(x, 3)) +
                (21.088120190111137475f),
        (17.044181459266411593f * x) - (48.94129365914702845f * powf(x, 2)) +
                (56.141270587723688834f * powf(x, 3)) + (1.6030780407930091958f)
    };

    Matrix<6, 1> err = refX_ - curX_;
    Matrix<2, 6> k(arrayK);

    if (_isFloating) {
        u_[0][0] = 0;
        u_[1][0] = err[0][0] * k[1][0] + err[0][1] * k[1][1];
    } else {
        u_ = k * err; // err = ref - cur
    }

    return u_;
}
